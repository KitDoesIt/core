const checkKey = (k: string | number, v: any): void => {
  if (typeof k === 'number') k = k.toString();

  if (
    k[0] === '$' &&
    !(k === '$$date' && typeof v === 'number') &&
    !(k === '$$deleted' && v === true) &&
    !k.startsWith('$$indexCreated') &&
    !k.startsWith('$$indexRemoved')
  )
    throw new Error('Field names cannot begin with the $ character');

  if (k.indexOf('.') !== -1) throw new Error('Field names cannot contain a .');
};

/**
 * Check a DB object and throw an error if it's not valid.
 * Works by applying the above checkKey function to all fields recursively.
 */
export const checkObject = (obj: any): void => {
  if (Array.isArray(obj)) {
    obj.forEach(o => {
      checkObject(o);
    });
  }

  if (typeof obj === 'object' && obj !== null) {
    for (const k in obj) {
      if (Object.prototype.hasOwnProperty.call(obj, k)) {
        checkKey(k, obj[k]);
        checkObject(obj[k]);
      }
    }
  }
};

/**
 * Serialize an object to be persisted to a one-line string.
 * Dates become `{ $$date: <ms> }`, undefined fields are dropped.
 */
export const serialize = (obj: any): string =>
  JSON.stringify(obj, function (this: any, k: string, v: any) {
    checkKey(k, v);

    if (v === undefined) return undefined;
    if (v === null) return null;

    // Hackish way of checking if object is Date (this way it works between
    // execution contexts). We can't use value directly because for dates it is
    // already string in this function (date.toJSON was already called).
    if (typeof this[k].getTime === 'function') return { $$date: this[k].getTime() };

    return v;
  });

/**
 * From a one-line representation of an object generated by the serialize
 * function, return the object itself.
 */
export const deserialize = (rawData: string): any =>
  JSON.parse(rawData, function (k: string, v: any) {
    if (k === '$$date') return new Date(v);
    if (
      typeof v === 'string' ||
      typeof v === 'number' ||
      typeof v === 'boolean' ||
      v === null
    )
      return v;
    if (v && v.$$date) return v.$$date;

    return v;
  });

/**
 * Deep copy a DB object.
 */
export const deepCopy = (obj: any, strictKeys?: boolean): any => {
  if (typeof obj === 'boolean' || typeof obj === 'number' || typeof obj === 'string' || obj === null || isDate(obj))
    return obj;

  if (Array.isArray(obj)) return obj.map(o => deepCopy(o, strictKeys));

  if (typeof obj === 'object') {
    const res: any = {};
    for (const k in obj) {
      if (Object.prototype.hasOwnProperty.call(obj, k) && (!strictKeys || (k[0] !== '$' && k.indexOf('.') === -1))) {
        res[k] = deepCopy(obj[k], strictKeys);
      }
    }
    return res;
  }

  return undefined;
};

export const isPrimitiveType = (obj: any): boolean =>
  typeof obj === 'boolean' || typeof obj === 'number' || typeof obj === 'string' || obj === null || isDate(obj) || Array.isArray(obj);

// ==============================================================
// Comparison
// ==============================================================

const compareNSB = (a: number | string | boolean, b: number | string | boolean): number => {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
};

const compareArrays = (a: any[], b: any[]): number => {
  const minLength = Math.min(a.length, b.length);
  for (let i = 0; i < minLength; i += 1) {
    const comp = compareThings(a[i], b[i]);
    if (comp !== 0) return comp;
  }
  return compareNSB(a.length, b.length);
};

/**
 * Compare { things U undefined }.
 * Type hierarchy: undefined, null, number, string, boolean, date, array, object.
 */
export const compareThings = (a: any, b: any, _compareStrings?: (a: string, b: string) => number): number => {
  const compareStrings = _compareStrings || compareNSB;

  // undefined
  if (a === undefined) return b === undefined ? 0 : -1;
  if (b === undefined) return 1;

  // null
  if (a === null) return b === null ? 0 : -1;
  if (b === null) return 1;

  // Numbers
  if (typeof a === 'number') return typeof b === 'number' ? compareNSB(a, b) : -1;
  if (typeof b === 'number') return typeof a === 'number' ? compareNSB(a, b) : 1;

  // Strings
  if (typeof a === 'string') return typeof b === 'string' ? compareStrings(a, b) : -1;
  if (typeof b === 'string') return typeof a === 'string' ? compareStrings(a, b) : 1;

  // Booleans
  if (typeof a === 'boolean') return typeof b === 'boolean' ? compareNSB(a, b) : -1;
  if (typeof b === 'boolean') return typeof a === 'boolean' ? compareNSB(a, b) : 1;

  // Dates
  if (isDate(a)) return isDate(b) ? compareNSB(a.getTime(), b.getTime()) : -1;
  if (isDate(b)) return isDate(a) ? compareNSB(a.getTime(), b.getTime()) : 1;

  // Arrays (first element is most significant and so on)
  if (Array.isArray(a)) return Array.isArray(b) ? compareArrays(a, b) : -1;
  if (Array.isArray(b)) return Array.isArray(a) ? compareArrays(a, b) : 1;

  // Objects
  const aKeys = Object.keys(a).sort();
  const bKeys = Object.keys(b).sort();

  for (let i = 0; i < Math.min(aKeys.length, bKeys.length); i += 1) {
    const comp = compareThings(a[aKeys[i]], b[bKeys[i]]);
    if (comp !== 0) return comp;
  }

  return compareNSB(aKeys.length, bKeys.length);
};

/**
 * Check whether 'things' are equal.
 */
export const areThingsEqual = (a: any, b: any): boolean => {
  // Strings, booleans, numbers, null
  if (
    a === null ||
    typeof a === 'string' ||
    typeof a === 'boolean' ||
    typeof a === 'number' ||
    b === null ||
    typeof b === 'string' ||
    typeof b === 'boolean' ||
    typeof b === 'number'
  )
    return a === b;

  // Dates
  if (isDate(a) || isDate(b)) return isDate(a) && isDate(b) && a.getTime() === b.getTime();

  // Arrays (no match since arrays are used as a $in)
  // undefined (no match since they mean field doesn't exist and can't be serialized)
  if (
    (!(Array.isArray(a) && Array.isArray(b)) && (Array.isArray(a) || Array.isArray(b))) ||
    a === undefined ||
    b === undefined
  )
    return false;

  // General objects (check for deep equality)
  let aKeys: string[];
  let bKeys: string[];
  try {
    aKeys = Object.keys(a);
    bKeys = Object.keys(b);
  } catch (e) {
    return false;
  }

  if (aKeys.length !== bKeys.length) return false;
  for (const el of aKeys) {
    if (bKeys.indexOf(el) === -1) return false;
    if (!areThingsEqual(a[el], b[el])) return false;
  }
  return true;
};

