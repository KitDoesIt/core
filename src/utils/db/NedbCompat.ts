/**
 * NeDB-compatible document model, query matcher and update engine.
 *
 * This is a TypeScript port of the relevant parts of `@seald-io/nedb`'s
 * `lib/model.js` and `lib/utils.js` (MIT licensed, https://github.com/seald/nedb).
 * It is kept semantically identical on purpose: the SQLite backend evaluates
 * queries/updates with these functions so that plugin-visible behaviour matches
 * the old NeDB store one to one.
 *
 * Ported functions: checkObject/checkKey, serialize/deserialize, deepCopy,
 * compareThings, areThingsEqual, getDotValue(s), match/matchQueryPart, modify
 * (all update modifiers) and uid().
 */

import { randomBytes } from 'crypto';

// ==============================================================
// utils (from lib/utils.js)
// ==============================================================

export const uniq = <T>(array: T[], iteratee?: (x: T) => any): T[] => {
  if (iteratee) return [...new Map(array.map(x => [iteratee(x), x])).values()];
  return [...new Set(array)];
};

const isObject = (arg: any): boolean => typeof arg === 'object' && arg !== null;

export const isDate = (d: any): d is Date =>
  isObject(d) && Object.prototype.toString.call(d) === '[object Date]';

export const isRegExp = (re: any): re is RegExp =>
  isObject(re) && Object.prototype.toString.call(re) === '[object RegExp]';

/**
 * Random alphanumerical string, same algorithm as NeDB's customUtils.uid.
 */
export const uid = (len: number): string =>
  randomBytes(Math.ceil(Math.max(8, len * 2)))
    .toString('base64')
    .replace(/[+/]/g, '')
    .slice(0, len);

